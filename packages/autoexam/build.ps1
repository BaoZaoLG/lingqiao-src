param (
    [string]$SourceFile = "..\..\AutoExam.js",
    [string]$OutDir = "dist"
)

$ErrorActionPreference = "Stop"

if (-not (Test-Path $SourceFile)) {
    Write-Error "Source file not found: $SourceFile"
}

# Create directories
$SrcDir = "src"
if (-not (Test-Path $SrcDir)) { New-Item -ItemType Directory -Path $SrcDir | Out-Null }
if (-not (Test-Path $OutDir)) { New-Item -ItemType Directory -Path $OutDir | Out-Null }

$ScriptContent = Get-Content $SourceFile -Raw
$ScriptBytes = [System.Text.Encoding]::UTF8.GetBytes($ScriptContent)

# 1. Copy source to src/ and dist/
Copy-Item $SourceFile -Destination "$SrcDir\autoexam.js" -Force
Copy-Item $SourceFile -Destination "$OutDir\autoexam.bundle.js" -Force

# 2. Calculate SHA256 and version metadata
$HashObj = [System.Security.Cryptography.SHA256]::Create()
$HashBytes = $HashObj.ComputeHash($ScriptBytes)
$Sha256Hex = [System.BitConverter]::ToString($HashBytes).Replace("-", "").ToLower()

$Version = Get-Date -Format "yyyyMMdd.HHmmss"

$Manifest = @{
    version = $Version
    sha256 = $Sha256Hex
    size = $ScriptBytes.Length
    created_at = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ssZ")
}
$Manifest | ConvertTo-Json | Out-File -FilePath "$OutDir\autoexam.manifest.json" -Encoding utf8 -Force

# 3. Encrypt and generate embedded header
Write-Host "Generating autoexam.embedded.h..."

function Encrypt-Chunk {
    param([byte[]]$Bytes)
    $Key = [BitConverter]::ToUInt64(([guid]::NewGuid().ToByteArray()), 0)
    $KeyBytes = [BitConverter]::GetBytes($Key)
    $Encrypted = New-Object byte[] $Bytes.Length
    for ($i = 0; $i -lt $Bytes.Length; $i++) {
        $Encrypted[$i] = $Bytes[$i] -bxor $KeyBytes[$i % 8] -bxor [byte](($i * 0x9D) -band 0xFF)
    }
    return @{ Key = $Key; Data = $Encrypted }
}

$HalfSize = [math]::Ceiling($ScriptBytes.Length / 2)
$P1 = $ScriptBytes[0..($HalfSize-1)]
$P2 = $ScriptBytes[$HalfSize..($ScriptBytes.Length-1)]

$Enc1 = Encrypt-Chunk $P1
$Enc2 = Encrypt-Chunk $P2

function Format-ByteArray {
    param([byte[]]$Bytes)
    $Sb = New-Object System.Text.StringBuilder
    for ($i = 0; $i -lt $Bytes.Length; $i++) {
        if ($i % 16 -eq 0) { [void]$Sb.Append("    ") }
        [void]$Sb.AppendFormat("0x{0:X2}, ", $Bytes[$i])
        if ($i % 16 -eq 15 -or $i -eq $Bytes.Length - 1) { [void]$Sb.AppendLine() }
    }
    return $Sb.ToString()
}

$HeaderContent = @"
// Auto-generated by packages/autoexam/build.ps1
// DO NOT EDIT MANUALLY

#pragma once
#include "obfuscate.h"

// JS Part 1
static const BYTE __g_enc_js_p1_data[] = {
$(Format-ByteArray $Enc1.Data)};
static const EncryptedBlob g_enc_js_p1 = {
    __g_enc_js_p1_data,
    $($Enc1.Data.Length),
    $($Enc1.Key)ULL
};

// JS Part 2
static const BYTE __g_enc_js_p2_data[] = {
$(Format-ByteArray $Enc2.Data)};
static const EncryptedBlob g_enc_js_p2 = {
    __g_enc_js_p2_data,
    $($Enc2.Data.Length),
    $($Enc2.Key)ULL
};
"@

Set-Content -Path "$OutDir\autoexam.embedded.h" -Value $HeaderContent -Encoding utf8
Write-Host "Done building autoexam package."
